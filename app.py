"""Streamlit interface for the CrewAI Travel Planning Agent."""

import logging
import os

import streamlit as st
from dotenv import load_dotenv

from travel_crew import TripRequest, TravelPlan, build_travel_crew, run_travel_crew, validate_trip_request


INTEREST_SUGGESTIONS = [
    "Culture & history",
    "Food & local markets",
    "Nature & outdoors",
    "Adventure",
    "Art & architecture",
    "Nightlife",
    "Family-friendly",
    "Shopping",
    "Relaxation",
]
BUDGET_OPTIONS = ["Not specified", "Budget", "Mid-range", "Premium"]
CURRENCIES = ["USD", "EUR", "GBP", "INR", "JPY", "AUD", "CAD"]

logger = logging.getLogger("travel_planning_agent")


# This logger keeps the app's AI workflow errors visible in the terminal and
# browser console during local development and debugging.
def configure_logging() -> None:
    if logger.handlers:
        return
    handler = logging.StreamHandler()
    handler.setFormatter(logging.Formatter("%(asctime)s - %(levelname)s - %(message)s"))
    logger.addHandler(handler)
    logger.setLevel(logging.INFO)
    logger.propagate = False


# Read API credentials from the environment first and then fall back to
# Streamlit's secret store when the app is running in a hosted environment.
def get_secret(name: str) -> str | None:
    """Read a secret from the environment first, then Streamlit secrets."""
    if value := os.getenv(name):
        return value
    try:
        value = st.secrets.get(name)
        if value:
            # CrewAI tools read credentials from the process environment.
            os.environ[name] = value
        return value
    except FileNotFoundError:
        return None


# Build the CrewAI team once per model and research mode so the app does not
# recreate the same agents and tools for every trip request.
@st.cache_resource(show_spinner=False)
def get_crew(model_name: str, use_live_research: bool):
    """Cache the static Crew configuration; trip inputs remain per-request."""
    return build_travel_crew(model_name, use_live_research)


# Turn a validated TravelPlan into a readable itinerary dashboard for the user.
def render_plan(plan: TravelPlan) -> None:
    st.subheader(f"{plan.destination} in {plan.trip_length_days} days")
    st.write(plan.trip_overview)

    metric_one, metric_two, metric_three = st.columns(3)
    metric_one.metric("Budget estimate", plan.budget_total_estimate)
    metric_two.metric("Travel style", plan.travel_style)
    metric_three.metric("Days planned", len(plan.daily_itinerary))

    st.subheader("Daily itinerary")
    for day in plan.daily_itinerary:
        with st.expander(f"Day {day.day_number}: {day.theme}", expanded=day.day_number == 1):
            st.caption(f"Estimated day spend: {day.estimated_daily_cost}")
            for activity in day.activities:
                st.markdown(f"**{activity.time_of_day} - {activity.activity}**")
                st.write(activity.description)
                st.caption(f"Area: {activity.area} | Estimated cost: {activity.estimated_cost}")
                if activity.practical_note:
                    st.info(activity.practical_note)
            st.markdown(f"**Getting around:** {day.transport_note}")

    st.subheader("Budget outline")
    st.dataframe(
        [item.model_dump() for item in plan.budget_outline],
        column_config={
            "category": "Category",
            "estimated_amount": "Estimated amount",
            "assumptions": "Assumptions",
        },
        hide_index=True,
        width="stretch",
    )

    left, right = st.columns(2)
    with left:
        st.subheader("Travel considerations")
        for item in plan.travel_considerations:
            st.markdown(f"- {item}")
    with right:
        st.subheader("Booking checklist")
        for item in plan.booking_checklist:
            st.markdown(f"- {item}")

    st.subheader("Sources used by the research agent")
    for source in plan.sources:
        st.markdown(f"- [{source.title}]({source.url}) - {source.note}")

    st.caption(plan.responsible_travel_note)


# Main app flow: load environment settings, validate credentials, collect the
# trip request from the form, run the agent crew, and show the final outcome.
def main() -> None:
    load_dotenv()
    configure_logging()
    st.set_page_config(page_title="Travel Planning Agent", page_icon="TP", layout="wide")

    st.title("Travel Planning Agent")
    st.caption("Live destination research and a practical, structured itinerary generated by a CrewAI team.")

    request_column, explanation_column = st.columns([3, 2])
    with request_column:
        with st.form("trip_request"):
            st.subheader("Plan your trip")
            destination = st.text_input("Destination *", placeholder="e.g., Kyoto, Japan")
            trip_length = st.number_input("Trip length (days) *", min_value=1, max_value=21, value=4, step=1)
            selected_interests = st.multiselect("Interests *", INTEREST_SUGGESTIONS)
            custom_interests = st.text_input("Anything else you enjoy?", placeholder="e.g., tea ceremonies, easy hikes")

            start_date = st.date_input("Start date (optional)", value=None)
            end_date = st.date_input("End date (optional)", value=None)

            optional_one, optional_two, optional_three = st.columns(3)
            with optional_one:
                travelers = st.number_input("Travelers", min_value=1, max_value=12, value=1, step=1)
            with optional_two:
                budget_level = st.selectbox("Budget level", BUDGET_OPTIONS)
            with optional_three:
                currency = st.selectbox("Currency", CURRENCIES)
            preferences = st.text_area(
                "Preferences or constraints",
                placeholder="e.g., vegetarian food, limited walking, boutique hotels",
                max_chars=500,
            )
            use_live_research = st.checkbox(
                "Use live travel research",
                value=True,
                help="Search current web sources with Serper. Disable this to create a plan without live research.",
            )
            submitted = st.form_submit_button("Research and build itinerary", type="primary", width="stretch")

    with explanation_column:
        st.subheader("How it works")
        st.markdown("**1. Travel Researcher** searches current web sources for activities, logistics, and indicative costs when live research is enabled.")
        st.markdown("**2. Itinerary Planner** turns that research into your day-by-day plan and budget.")
        st.markdown("**3. CrewAI** runs both tasks sequentially and returns a validated structured report.")
        st.info("Pricing, availability, rules, and opening hours can change. Confirm critical details before booking.")

    if not submitted:
        return

    required_keys = ["OPENAI_API_KEY"]
    if use_live_research:
        required_keys.append("SERPER_API_KEY")
    missing_keys = [name for name in required_keys if not get_secret(name)]
    if missing_keys:
        st.error(f"Set {', '.join(missing_keys)} in your environment or Streamlit secrets before planning a trip.")
        st.code('OPENAI_API_KEY="your-openai-key"\nSERPER_API_KEY="your-serper-key"', language="toml")
        return

    interests = selected_interests + ([custom_interests.strip()] if custom_interests.strip() else [])
    errors = validate_trip_request(destination, int(trip_length), interests, start_date, end_date)
    if errors:
        for error in errors:
            st.error(error)
        return

    trip_request = TripRequest(
        destination=destination.strip(),
        trip_length_days=int(trip_length),
        interests=interests,
        start_date=start_date.isoformat() if start_date else None,
        end_date=end_date.isoformat() if end_date else None,
        travelers=int(travelers),
        budget_level=None if budget_level == "Not specified" else budget_level,
        currency=currency,
        preferences=preferences.strip() or None,
    )

    status = st.status("CrewAI is working on your trip...", expanded=True)
    try:
        status.write("Travel Researcher is gathering current destination information.")
        crew = get_crew(os.getenv("OPENAI_MODEL", "gpt-4o-mini"), use_live_research)
        plan, crew_result = run_travel_crew(crew, trip_request)
        status.write("Itinerary Planner has created the structured trip plan.")
        status.update(label="Travel plan ready", state="complete", expanded=False)
        render_plan(plan)
        with st.expander("CrewAI execution result (raw JSON)"):
            st.json(plan.model_dump(mode="json"))
            st.caption(f"Crew output: {crew_result.raw}")
    except ValueError as error:
        logger.warning("Travel plan validation failed: %s", error)
        status.update(label="Travel plan could not be created", state="error", expanded=True)
        st.error(str(error))
    except Exception:
        logger.exception("Crew execution failed")
        status.update(label="Travel plan could not be created", state="error", expanded=True)
        st.error("The travel crew could not complete the request. Check your API keys, Serper quota, and network connection, then try again.")


if __name__ == "__main__":
    main()
